// Bundles each Edge Function in supabase/functions-src/ into one
// self-contained supabase/functions/<name>/index.ts, with the _shared/
// files it imports built in. The Supabase web editor only uploads
// index.ts, so a function that imports ../_shared/ fails to deploy there.
//
// Run `npm run build:functions` after changing a file in
// supabase/functions-src/ or supabase/functions/_shared/, then deploy the
// generated index.ts (paste it into the web editor, or use the CLI).
// `--check` builds without writing and fails if any index.ts is out of
// date (coffeeDay.test.js runs it).

import { build } from 'esbuild';
import { readdirSync, readFileSync } from 'fs';
import path from 'path';

const SRC = 'supabase/functions-src';
const check = process.argv.includes('--check');
let stale = false;

for (const file of readdirSync(SRC).filter((f) => f.endsWith('.ts'))) {
  const name = path.basename(file, '.ts');
  const outfile = `supabase/functions/${name}/index.ts`;
  const result = await build({
    entryPoints: [path.join(SRC, file)],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    external: ['jsr:*', 'npm:*'],
    legalComments: 'none',
    outfile,
    write: !check,
    banner: {
      js: [
        '// @ts-nocheck',
        `// GENERATED by \`npm run build:functions\` from ${SRC}/${file} and the`,
        '// supabase/functions/_shared/ files it imports. Edit those, then rebuild;',
        '// changes made here are lost. This file is what gets deployed.',
        '',
      ].join('\n'),
    },
  });
  if (!check) {
    console.log(`Built ${outfile}`);
  } else if (result.outputFiles[0].text !== readFileSync(outfile, 'utf8')) {
    console.error(`${outfile} is out of date: run npm run build:functions`);
    stale = true;
  }
}
if (stale) process.exit(1);
